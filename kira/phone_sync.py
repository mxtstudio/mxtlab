"""Phone sync – generate a concise snapshot of the device's storage and store it in Kira's memory.

The function walks the public internal storage (``/sdcard``) and creates a markdown file
named ``phone_snapshot.md`` inside the memory directory (``~/.claude/projects/-data-data-com-termux-files-home/memory``).
Only the top‑level folders and a count of their immediate children are recorded – this keeps the
snapshot small while still giving a quick overview of what is on the device.
"""

import os
from pathlib import Path

# Path to Kira's memory folder – same location used by the memory subsystem.
MEMORY_ROOT = Path(os.path.expanduser("~/.claude/projects/-data-data-com-termux-files-home/memory"))

def generate_phone_snapshot(max_depth: int = 2) -> dict:
    """Create ``phone_snapshot.md`` summarising the device storage.

    Args:
        max_depth: How many directory levels to descend (default 2). ``1`` lists only the
                    top‑level folders; ``2`` also lists the files inside each top‑level folder.

    Returns:
        A dictionary with ``"path"`` (the markdown file written) and ``"summary"``
        describing how many top‑level items were processed.
    """
    storage_root = Path("/sdcard")
    if not storage_root.is_dir():
        raise FileNotFoundError("/sdcard does not exist on this device")

    markdown_lines = ["# Phone storage snapshot", "", "Generated by Kira (phone_sync) on " + os.popen('date').read().strip(), ""]
    total_top = 0
    total_items = 0

    for top_entry in sorted(storage_root.iterdir()):
        if not top_entry.name.startswith('.'):  # skip hidden system dirs
            total_top += 1
            if top_entry.is_dir():
                markdown_lines.append(f"## {top_entry.name}/")
                if max_depth > 1:
                    # List immediate children of this top‑level folder
                    children = sorted(top_entry.iterdir())
                    for child in children:
                        prefix = "- "
                        if child.is_dir():
                            markdown_lines.append(f"{prefix}{child.name}/")
                        else:
                            markdown_lines.append(f"{prefix}{child.name}")
                        total_items += 1
                markdown_lines.append("")
            else:
                markdown_lines.append(f"- {top_entry.name}")
                total_items += 1
                markdown_lines.append("")

    markdown_content = "\n".join(markdown_lines)
    # Ensure the memory folder exists
    MEMORY_ROOT.mkdir(parents=True, exist_ok=True)
    snapshot_path = MEMORY_ROOT / "phone_snapshot.md"
    snapshot_path.write_text(markdown_content, encoding="utf-8")

    return {"path": str(snapshot_path), "summary": f"Processed {total_top} top‑level entries, {total_items} items listed"}
